/**
 * Tiny className combiner (clsx-lite). Joins truthy class fragments with a
 * space; later values do NOT de-duplicate Tailwind conflicts, so order your
 * overrides last. Kept dependency-free on purpose.
 */
export type ClassValue =
  | string
  | number
  | null
  | false
  | undefined
  | ClassValue[];

export function cn(...inputs: ClassValue[]): string {
  const out: string[] = [];
  for (const input of inputs) {
    if (!input) continue;
    if (Array.isArray(input)) {
      const nested = cn(...input);
      if (nested) out.push(nested);
    } else {
      out.push(String(input));
    }
  }
  return out.join(" ");
}
